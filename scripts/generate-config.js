/**
 * scripts/generate-config.js
 * ============================================================
 * Reads SUPABASE_URL and SUPABASE_ANON_KEY from the environment
 * (or from a local .env file during development) and writes
 * js/config.js — which is .gitignore'd so keys never hit Git.
 *
 * Vercel runs: node scripts/generate-config.js  (via buildCommand)
 * Local dev:   node scripts/generate-config.js  (after setting .env)
 * ============================================================
 */

'use strict';

const fs   = require('fs');
const path = require('path');

// Load .env file in local development (harmless if file is missing)
try {
  require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
} catch (e) {
  // dotenv not installed — relying on shell env (fine on Vercel)
}

const url  = (process.env.SUPABASE_URL  || '').trim();
const anon = (process.env.SUPABASE_ANON_KEY || '').trim();

if (!url || !anon) {
  console.error(
    '\n❌  SUPABASE_URL or SUPABASE_ANON_KEY is not set.' +
    '\n    Copy .env.example → .env, fill in your values, and rerun.\n'
  );
  // Don't fail the build — write a stub so the site at least loads.
}

const configPath = path.join(__dirname, '..', 'js', 'config.js');

const content = `// ============================================================
// js/config.js — AUTO-GENERATED by scripts/generate-config.js
// DO NOT edit manually. DO NOT commit to Git (.gitignore'd).
// To regenerate: node scripts/generate-config.js
// ============================================================

window.SUPABASE_URL      = ${JSON.stringify(url)};
window.SUPABASE_ANON_KEY = ${JSON.stringify(anon)};
`;

fs.writeFileSync(configPath, content, 'utf8');
console.log('✅  js/config.js generated successfully');
